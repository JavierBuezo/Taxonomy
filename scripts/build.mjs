import {mkdir,copyFile,readFile,writeFile} from 'node:fs/promises';
const {version}=JSON.parse(await readFile('package.json','utf8'));
const name=`taxonomy-${version}.js`;
const sources=['activities.js','diagrams.js','model.js','app.js'];
let code='/* Taxonomy '+version+' — generated by npm run build */\n(function(){\n"use strict";\n';
for(const file of sources){let source=await readFile(file,'utf8');source=source.replace(/^import\s+[^\n]+;\s*$/gm,'').replace(/^export\s+/gm,'');code+=`\n// ${file}\n${source}\n`;}
code+='\n})();\n';
await writeFile(name,code);
let html=await readFile('index.html','utf8');
html=html.replace(/src="\.\/taxonomy-[\d.]+\.js"/,`src="./${name}"`);
await writeFile('index.html',html);
await mkdir('dist',{recursive:true});
for(const file of ['index.html','style.css',...sources,name])await copyFile(file,`dist/${file}`);
console.log(`Sitio estático preparado: ${name} (sin imports de red).`);
